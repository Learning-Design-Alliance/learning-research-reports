def unmarked(path: Path) -> bytes:
    """Published text files carry an embargo line while the release is embargoed; compare without it."""
    data = path.read_bytes()
    if path.suffix in (".md", ".txt", ".yaml", ".yml"):
        data = b"".join(ln for ln in data.splitlines(keepends=True) if b"LDA-" + b"EMBARGO" not in ln)
    return data


def same(new: Path, old: Path, mode: str) -> bool:
    if not new.exists():
        return False
    if mode == "rows":       # the atlas: the same rows, whatever order --only reruns merged them in
        key = lambda rows: sorted(json.dumps(r, sort_keys=True) for r in rows)  # noqa: E731
        return key(json.loads(new.read_text())) == key(json.loads(old.read_text()))
    if mode == "latent-gate":
        # The published kappa_bar_floor.json was written at 7f7214c; the script as declared (39735267) adds,
        # to each point, the `latent_gate` oracle its post hoc diagnostic introduced. Every other value
        # must be identical.
        def strip(x):
            if isinstance(x, dict):
                return {k: strip(v) for k, v in x.items() if k != "latent_gate"}
            return [strip(v) for v in x] if isinstance(x, list) else x
        return strip(json.loads(new.read_text())) == json.loads(old.read_text())
    if mode == "timing":
        # The script writes its own wall-clock time into its output, which no rerun can reproduce. Every
        # other field must be identical; only these keys are set aside.
        return drop_keys(json.loads(new.read_text()), TIMING_KEYS) == drop_keys(json.loads(old.read_text()),
                                                                              TIMING_KEYS)
    if mode == "close":
        # Floating-point summation order (numpy, BLAS) moves the last digits of some estimates between
        # machines. Text and integers must be identical; floats must agree to a relative 1e-6.
        return close(json.loads(new.read_text()), json.loads(old.read_text()))
    return unmarked(new) == unmarked(old)


TIMING_KEYS = {"seconds", "seconds_per_set", "seconds_per_fit", "calibrate_seconds"}


def drop_keys(x, keys):
    if isinstance(x, dict):
        return {k: drop_keys(v, keys) for k, v in x.items() if k not in keys}
    return [drop_keys(v, keys) for v in x] if isinstance(x, list) else x


def close(a, b) -> bool:
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(close(a[k], b[k]) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(close(x, y) for x, y in zip(a, b))
    if isinstance(a, float) and isinstance(b, float):
        return math.isclose(a, b, rel_tol=1e-6, abs_tol=1e-12)
    return type(a) is type(b) and a == b


def missing_needs(step) -> list[str]:
    out = []
    for n in step["needs"]:
        if n == MODEL:
            out.append("a hosted model (the recorded outputs are published; a prompt cannot be re-sent)")
        elif n == GPU:
            out.append("a machine with CUDA graphics processors (see the study's README; outputs are published)")
        elif n == WORKBOOK:
            out.append("the coder's returned workbook, which is not published (out/human-codes.json holds the codes)")
        else:
            var, _, rest = n.partition("/")
            v = os.environ.get(var)
            if not v or not (Path(v) / rest if rest else Path(v)).exists():
                out.append(n if not rest else f"{var} holding {rest}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[1], formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--only", nargs="*", help="step ids, or prefixes such as rq1, rq2-raise")
    ap.add_argument("--quick", action="store_true", help="skip the slow steps")
    ap.add_argument("--no-corpus", action="store_true", help="only the steps that read no corpus")
    ap.add_argument("--timeout", type=float, default=None, help="seconds allowed per step (default: none)")
    ap.add_argument("--work", type=Path, default=HERE / "reproduction", help="working folder (default ./reproduction)")
    a = ap.parse_args()

    if a.list:
        print(f"{'step':34s} {'RQ':6s} {'analysis':40s} needs / reproduces")
        for s in STEPS:
            needs = ", ".join(s["needs"]) or "no corpus"
            print(f"{s['id']:34s} {s['rq']:6s} {s['analysis'] or '':40s} [{needs}{', slow' if s['slow'] else ''}]"
                  f"\n{'':78s}{s['what']}")
        return 0

    steps = [s for s in STEPS if not a.only or any(s["id"] == o or s["id"].startswith(o) for o in a.only)]
    if a.quick:
        steps = [s for s in steps if not s["slow"]]
    if a.no_corpus:
        steps = [s for s in steps if not s["needs"]]
    work = a.work / "code"
    if work.exists():
        shutil.rmtree(work)
    shutil.copytree(CODE, work, ignore=shutil.ignore_patterns("__pycache__"))
    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}

    results = []
    for s in steps:
        miss = missing_needs(s)
        if miss:
            results.append((s["id"], s["rq"], "SKIPPED", "needs " + "; ".join(miss)))
            continue
        line = s["cmd"]
        for var in ("JUNYI_DIR", "DS1275_DIR", "MOOCCUBEX_DIR", "LT_C6_XLSX", "LDA_SCRATCH_DIR"):
            line = line.replace("{" + var + "}", shlex.quote(os.environ.get(var, "")))  # paths may hold spaces
        cwd = work / s["cwd"]
        for c in s["clean"]:
            p = cwd / c
            shutil.rmtree(p) if p.is_dir() else p.unlink(missing_ok=True)
        print(f"\n[{s['id']}] {s['what']}\n  (cd code/{s['cwd']} && python3 {s['cmd']})", flush=True)
        t0 = time.time()
        try:
            r = subprocess.run([sys.executable, *shlex.split(line)], cwd=cwd, env={**env, **s["env"]},
                               timeout=a.timeout)
        except subprocess.TimeoutExpired:
            results.append((s["id"], s["rq"], "TIMEOUT", f"stopped after {a.timeout:.0f} s"))
            continue
        took = time.time() - t0
        # a registered floor that fails exits 1 by design; its record is still compared
        ok_exit = r.returncode == 0 or (s["compare"].endswith("-exit1") and r.returncode == 1)
        if not ok_exit:
            results.append((s["id"], s["rq"], "FAILED", f"exit {r.returncode} after {took:.0f} s"))
            continue
        mode = s["compare"].removesuffix("-exit1")      # bytes, rows, latent-gate, timing or close
        diff = [o for o in s["outs"] if not same(cwd / o, CODE / s["cwd"] / o, mode)]
        detail = (", ".join(diff) if diff else
                  f"{len(s['outs'])} file(s) {'identical' if s['outs'] else 'to compare (writes none)'}, {took:.0f} s")
        results.append((s["id"], s["rq"], "DIFFERS" if diff else "MATCH", detail))

    print("\n" + "=" * 110)
    print(f"{'step':34s} {'RQ':6s} {'result':8s} detail")
    for sid, rq, status, detail in results:
        print(f"{sid:34s} {rq:6s} {status:8s} {detail}")
    n = {k: sum(r[2] == k for r in results) for k in ("MATCH", "DIFFERS", "SKIPPED", "TIMEOUT", "FAILED")}
    print(f"\n{n['MATCH']} match, {n['DIFFERS']} differ, {n['SKIPPED']} skipped, {n['TIMEOUT']} timed out, "
          f"{n['FAILED']} failed.")
    return 1 if n["DIFFERS"] or n["FAILED"] else 0


if __name__ == "__main__":
    sys.exit(main())
