#!/usr/bin/env python3
"""
reproduce.py: recompute the results of release learning-graph-budget-2026 (Paper II, "What learner
records can say about a prerequisite edge") from what is published with it, and check each against the
published output.

    python3 reproduce.py                    every step that the data on this machine allow
    python3 reproduce.py --list             the steps, which result each reproduces, and what it needs
    python3 reproduce.py --only rq2 rq5-ld  just some steps (a step id, or a prefix such as rq1)
    python3 reproduce.py --no-corpus        only the steps that read no corpus (simulations, floors,
                                            and steps that read committed outputs)
    python3 reproduce.py --quick            skip the slow steps (minutes to hours each)

WHAT IT DOES. It copies the code package (code/) to a working folder, runs each analysis exactly as the
release file (1.0.0.yaml, analyses:) records it, from the study's own directory, and compares every file
the step writes, byte for byte, with the published copy in code/. It never changes code/. Steps run in
the order listed, so a floor regenerated by one step is the floor the next step reads. At the end it
prints one line per step: MATCH, DIFFERS (with the file), SKIPPED (with what is missing), TIMEOUT or
FAILED.

WHAT IT NEEDS. Python 3.11 with numpy and scipy; the trajectory-order step also needs pandas, openpyxl
and statsmodels. No step calls a model: the steps that did (building the graph, mapping units to Common
Core clusters, tagging, the coverage judge) are listed and always skipped, because a prompt cannot be
re-sent from the release; their recorded outputs are published in code/. Most steps read a licensed
corpus, which you obtain yourself (the licences forbid redistributing it here). Point each environment
variable at your copy; a step whose corpus is absent is skipped, not failed. The release file
(datasets:) gives where each corpus comes from and the SHA-256 of the bytes the analyses read.

    XES_DIR          XES3G5M: attempts.tsv, cid2route.json, XES3G5M/metadata/questions.json
    ASSIST_DIR       ASSISTments 2012-13: assist2012.zip, assist_rich.csv, assist_skill_names.csv
    EDMCUP_DIR       EDM Cup 2023: the official CSVs (and cells.tsv, which the edmcup-prep step writes)
    EDNET_ZIP        EdNet KT1 archive; EDNET_CONTENTS: its contents/ folder (questions.csv)
    EEDI_ZIP         Eedi NeurIPS 2020 data.zip; EEDI_ANSWERS: answers.tsv made from it
    SLAM_DIR         Duolingo SLAM 2018 files;  DATASHOP_DIR, DS1275_DIR, DS576_DIR: DataShop exports
    JUNYI_DIR        Junyi 2015: exercise table, rating files, problem-log sample
    JUNYI2020_DIR    Junyi 2020 (Kaggle): junyi2020.zip, Log_Problem.csv, Info_Content.csv
    MOOCCUBEX_DIR    MOOCCubeX: attempts.tsv, concept-problem.txt, user-order.jsonl
    ECPE_DIR         ECPE: ecpe_responses.csv, ecpe_qmatrix.csv
    LDA_SCRATCH_DIR  a folder holding osf-59shv/exp.zip (ASSISTments experiments) and ds1190/ (the
                     ds1190 per-sample exports); scripts find these two through it
    LT_C6_XLSX       the file "C6 Analysis File.xlsx" from ICPSR 151741 (this script's own variable)

The data/ingest scripts in code/data/ingest/ rebuild the derived files (assist_rich.csv, answers.tsv,
attempts.tsv, user-order.jsonl, the ECPE csvs) from the deposited files byte for byte.
"""
