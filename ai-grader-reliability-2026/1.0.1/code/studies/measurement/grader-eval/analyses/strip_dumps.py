#!/usr/bin/env python3
"""
strip_dumps.py — the publishable copy of the per-case model outputs of release
ai-grader-reliability-2026 (Paper VI), and the way back from it to the files the analyses read.

WHY. Every re-test figure in the release is regenerated by a declared analysis from the per-case
harness dumps of its model runs (32 JSON files; SHA-256 values in per-case-dumps.sha256 beside this
file, paths relative to the dump directory). Those dumps were held privately in the session
scratchpad, so no reader could re-run a single re-test number. The maintainer decided on 2026-10-06
to publish stripped copies with the release. This script makes them, deterministically, from the
hashed dumps, and rebuilds analysis-ready dumps from them.

WHAT IS KEPT, per graded case: the corpus, the case id, the learner, submission or essay id as the
corpus publishes it (JorGPT `entry_id` and `student_anom_id`; Mohler `id`; Menagerie
`assignment_number` and rubric `skill`; ASAP 2.0 `essay_id`), the question or task, the label or
exemplar marks shown in each arm, the human score(s) the corpus ships, the model id and the model's
mark in each arm, plus the harness's numeric bookkeeping that an analysis reads (the attainment tail,
the scale maximum, answer and context lengths in characters, the exemplar anchors' case ids and
rotation). Run-level headers (model, run stamp, arms, scale, labels, call and token counts, the
request-configuration record with prompt bodies already reduced to hashes) are kept on one `run`
line per run in the same file.

WHAT IS REMOVED. The dumps carry no answer, essay or program text and no grader rationale or
evaluation text: the harness never wrote them (checked by this script: any string value longer than
80 characters anywhere in a row, or any row key outside the allow-list, is a hard error). What is
removed is the ASAP 2.0 demographic block (`groups`: English-learner, economic, disability,
race/ethnicity, gender) and the sampling cell derived from it (`cell`), and one header field naming a
local session path (`resumedFrom`). The demographic fields are public in the corpus and are re-joined
by essay id when the dumps are rebuilt.

WHAT IT READS.
  - the 32 dumps (model outputs, not a corpus), each checked against per-case-dumps.sha256 first;
  - for `rebuild --asap2` and `verify`: the ASAP 2.0 corpus file ASAP2_train_sourcetexts.csv
    (data/data-sources.json `asap2`, CC BY 4.0, $ASAP2_DIR), for essay_id, ell_status,
    economically_disadvantaged, student_disability_status, race_ethnicity and gender only, to re-join
    the demographic fields the published copy leaves out. Nothing from the corpus is written to the
    repository.

USAGE (from the repository root; D is the dump directory):

  python3 studies/measurement/grader-eval/analyses/strip_dumps.py strip --dump-dir D
      verify the 32 hashes, write per-case-model-outputs.jsonl beside the release file
      (research/wiki/research/releases/ai-grader-reliability-2026/), print its sha256, line counts
      and bytes. Deterministic: a second run is byte-identical.

  python3 .../strip_dumps.py rebuild --out R [--asap2 <ASAP2_train_sourcetexts.csv>]
      write R/<run>.json for every run, in the layout the analyses read (same relative paths as
      the original dump directory, so R can be passed wherever the release says <D>). The two ASAP
      2.0 runs need --asap2 (else $ASAP2_DIR via shared.paths), because their analyses read the
      demographic fields.
      Each file is written as the harness wrote it (JSON, indent 2, no trailing newline), so 30 of the 32 rebuilt files are byte-identical to the originals and match per-case-dumps.sha256; the two
      ASAP 2.0 runs differ only by the removed `resumedFrom` header field.

  python3 .../strip_dumps.py verify --dump-dir D [--asap2 ...]
      rebuild in memory and compare with the original dumps: every row equal in value and key order,
      every header equal except the removed field. Proves the stripped copy plus the public corpus
      is the whole of what the analyses read. D may also be a directory written by `rebuild`: each
      file must then match per-case-dumps.sha256 or, for the two ASAP 2.0 runs, which lose
      `resumedFrom`, per-case-dumps.rebuilt.sha256 (reproduction-13, note O3).

FORMAT. ONE file, per-case-model-outputs.jsonl (maintainer, 2026-10-06: one file that travels with
the release's deposit). One JSON object per line, with a `record` key. First, 32 `record: "run"`
lines in manifest order (the run id, corpus, model, source dump and its sha256, case count, the
harness's original row-key and header-key order, the keys removed, and the stripped header). Then
one `record: "case"` line per graded case per run: `record`, `run`, `corpus`, `model`, then the
harness's own row keys in the harness's order. The data dictionary is
per-case-model-outputs.README.md beside it.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "per-case-dumps.sha256"
REBUILT = HERE / "per-case-dumps.rebuilt.sha256"   # the two ASAP 2.0 dumps as `rebuild` writes them
OUTFILE = "per-case-model-outputs.jsonl"
DATA = ROOT / "research/wiki/research/releases/ai-grader-reliability-2026"
if not DATA.is_dir() and (ROOT.parent / OUTFILE).is_file():
    DATA = ROOT.parent   # run from the release's code package: code/ sits beside the published file

REMOVED_ROW = ("groups", "cell")          # ASAP 2.0 demographics, and the cell derived from them
REMOVED_HEADER = ("resumedFrom",)          # a local session path
ADDED = ("record", "run", "corpus", "model")

# Every row key the harness wrote, by meaning (see per-case-model-outputs.README.md). Anything else is refused, so a
# future dump that carries text cannot be published by this script without someone reading it.
ALLOWED_ROW = {
    "id", "questionId", "learnerId", "cluster", "dim", "tail", "prompt",          # identifiers
    "human", "max", "chars", "labelTrueChars",                                     # reference, scale, lengths
    "labelTrue", "labelSwapped", "labelHigh", "labelLow",                          # label shown
    "control", "trueLabel", "swappedLabel", "high", "low", "none", "mid", "neutral",  # marks per arm
    "no history (control)", "prior attempt, low grade", "prior attempt, high grade",
    "prior attempt, low, NO mark", "prior attempt, high, NO mark",
    "lite", "standard",                                                            # pooling marks
    "anchorIds", "trueMarks", "rotation", "shown", "contextChars", "scores",       # exemplar arms
    *REMOVED_ROW,
}
MAX_STR = 80


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def manifest(path: Path = MANIFEST) -> list[tuple[str, str]]:
    out = []
    for line in path.read_text().splitlines():
        if line.strip():
            digest, rel = line.split(None, 1)
            out.append((digest, rel.strip()))
    return out


def corpus_of(rel: str, header: dict) -> str:
    if header.get("corpus"):
        return header["corpus"]
    top = rel.split("/")[0]
    if top in ("grader-vi", "breadth", "exmarks", "reproduction-rerun", "fable-agent", "neutral"):
        return "jorgpt"
    raise SystemExit(f"{rel}: cannot tell which corpus this dump is from")


def check_row(rel: str, i: int, row: dict) -> None:
    extra = set(row) - ALLOWED_ROW
    if extra:
        raise SystemExit(f"{rel} row {i}: keys outside the allow-list {sorted(extra)}; read them first")
    if set(ADDED) & set(row):
        raise SystemExit(f"{rel} row {i}: a row key collides with an added column")

    def walk(v, where):
        if isinstance(v, str) and len(v) > MAX_STR and not where.startswith("groups"):
            raise SystemExit(f"{rel} row {i} {where}: a {len(v)}-character string; text is not published")
        if isinstance(v, dict):
            for k, x in v.items():
                walk(x, f"{where}.{k}" if where else k)
        elif isinstance(v, list):
            for x in v:
                walk(x, where)
    walk(row, "")


def load_dumps(dump_dir: Path, accept_rebuilt: bool = False) -> list[tuple[str, str, dict]]:
    """The 32 dumps, each checked against per-case-dumps.sha256. With accept_rebuilt (verify only, never
    strip), a dump may instead match per-case-dumps.rebuilt.sha256, as `rebuild` writes the ASAP 2.0 runs."""
    rebuilt = {rel: digest for digest, rel in manifest(REBUILT)} if accept_rebuilt else {}
    dumps = []
    for digest, rel in manifest():
        p = dump_dir / rel
        if not p.is_file():
            raise SystemExit(f"missing dump {p}")
        got = sha256(p)
        if got != digest and got != rebuilt.get(rel):
            also = " or per-case-dumps.rebuilt.sha256" if rel in rebuilt else ""
            raise SystemExit(f"{rel}: sha256 {got} does not match per-case-dumps.sha256 ({digest}){also}")
        dumps.append((rel, digest, json.loads(p.read_text(encoding="utf-8"))))
    return dumps


def dumps_line(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"), allow_nan=False)


def strip(dump_dir: Path, out_dir: Path) -> None:
    dumps = load_dumps(dump_dir)
    runs, lines = [], []
    for rel, digest, blob in dumps:
        header = {k: v for k, v in blob.items() if k != "rows" and k not in REMOVED_HEADER}
        rows = blob["rows"]
        run = rel[:-5] if rel.endswith(".json") else rel
        corpus = corpus_of(rel, blob)
        model = blob.get("model") if "model" in blob else blob.get("models")
        row_keys: list[str] = []
        for i, r in enumerate(rows):
            check_row(rel, i, r)
            for k in r:
                if k not in row_keys:
                    row_keys.append(k)
            kept = {k: v for k, v in r.items() if k not in REMOVED_ROW}
            lines.append(dumps_line({"record": "case", "run": run, "corpus": corpus, "model": model,
                                     **kept}))
        runs.append(dumps_line({
            "record": "run", "run": run, "corpus": corpus, "model": model,
            "source": rel, "source_sha256": digest, "cases": len(rows),
            "row_keys": row_keys,
            "removed_row_keys": [k for k in REMOVED_ROW if k in row_keys],
            "removed_header_keys": [k for k in REMOVED_HEADER if k in blob],
            "header_keys": [k for k in blob],
            "header": header,
        }))
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / OUTFILE
    p.write_text("".join(l + "\n" for l in runs + lines), encoding="utf-8")
    print(f"{sha256(p)}  {OUTFILE}  {len(runs)} run lines + {len(lines)} case lines  "
          f"{p.stat().st_size} bytes")


def asap2_groups(path: Path) -> dict[str, dict]:
    """essay_id -> (groups, cell), exactly as harness/asap2.ts loadAsap2 and quotaCell build them."""
    csv.field_size_limit(1 << 30)
    out = {}
    with path.open(encoding="utf-8", newline="") as fh:
        for r in csv.DictReader(fh):
            g = {"ell": r["ell_status"] or "NA",
                 "economic": r["economically_disadvantaged"] or "NA",
                 "disability": r["student_disability_status"] or "NA",
                 "race": r["race_ethnicity"] or "NA",
                 "gender": r["gender"] or "NA"}
            cell = ("ell" if g["ell"] == "Yes" else
                    "disability" if g["disability"] == "Identified as having disability" else "rest")
            out[r["essay_id"]] = {"groups": g, "cell": cell}
    return out


def resolve_asap2(arg: str | None) -> Path:
    if arg:
        return Path(arg)
    sys.path.insert(0, str(ROOT))
    from shared.paths import data_path
    return data_path("ASAP2_DIR") / "ASAP2_train_sourcetexts.csv"


def rebuild_all(data_dir: Path, asap2: str | None, skip_missing: bool = False) -> dict[str, dict]:
    runs, by_run = [], {}
    with (data_dir / OUTFILE).open(encoding="utf-8") as fh:
        for line in fh:
            rec = json.loads(line)
            if rec["record"] == "run":
                runs.append(rec)
                by_run[rec["run"]] = []
            else:
                by_run[rec["run"]].append(rec)
    join = None
    out = {}
    for r in runs:
        rows = by_run[r["run"]]
        if len(rows) != r["cases"]:
            raise SystemExit(f"{r['run']}: {len(rows)} case lines, its run line says {r['cases']}")
        if r["removed_row_keys"] and join is None:
            try:
                join = asap2_groups(resolve_asap2(asap2))
            except (SystemExit, FileNotFoundError, KeyError) as exc:
                if not skip_missing:
                    raise
                print(f"skipped {r['run']}: it needs the ASAP 2.0 corpus to re-join its demographic fields ({exc})")
                continue
        built = []
        for rec in rows:
            src = {k: v for k, v in rec.items() if k not in ADDED}
            if r["removed_row_keys"]:
                src.update(join[src["id"]])
            built.append({k: src[k] for k in r["row_keys"] if k in src})
        out[r["source"]] = {k: (built if k == "rows" else r["header"][k])
                            for k in r["header_keys"] if k == "rows" or k in r["header"]}
    return out


def rebuild(data_dir: Path, out_dir: Path, asap2: str | None, skip_missing: bool = False) -> None:
    built = rebuild_all(data_dir, asap2, skip_missing)
    for rel, blob in built.items():
        p = out_dir / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        # indent=2 and no trailing newline: the harness's own serialisation, so a rebuilt dump is byte-identical
        # to its original (30 of 32; the two ASAP 2.0 dumps lose `resumedFrom`) and passes analyses that check
        # each dump's sha256 against per-case-dumps.sha256, as grader-ceiling-robustness does (scope-audit-6 S8).
        p.write_text(json.dumps(blob, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"rebuilt {len(built)} of {len(manifest())} dumps under {out_dir}")


def verify(dump_dir: Path, data_dir: Path, asap2: str | None) -> None:
    built = rebuild_all(data_dir, asap2)
    bad = 0
    for rel, _digest, blob in load_dumps(dump_dir, accept_rebuilt=True):
        b = built[rel]
        rows_ok = (len(b["rows"]) == len(blob["rows"]) and
                   all(x == y and list(x) == list(y) for x, y in zip(b["rows"], blob["rows"])))
        h_src = {k: v for k, v in blob.items() if k != "rows" and k not in REMOVED_HEADER}
        h_b = {k: v for k, v in b.items() if k != "rows"}
        head_ok = h_src == h_b
        ok = rows_ok and head_ok
        bad += not ok
        print(f"  {'OK  ' if ok else 'DIFF'} {rel}  rows {'equal' if rows_ok else 'DIFFER'}, "
              f"header {'equal' if head_ok else 'DIFFERS'}"
              + (f" (less {', '.join(k for k in REMOVED_HEADER if k in blob)})"
                 if any(k in blob for k in REMOVED_HEADER) else ""))
    print(f"VERIFY {'PASS' if not bad else 'FAIL'}: {len(built) - bad} of {len(built)} dumps rebuilt exactly")
    sys.exit(1 if bad else 0)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("strip"); s.add_argument("--dump-dir", required=True); s.add_argument("--out", default=str(DATA))
    b = sub.add_parser("rebuild"); b.add_argument("--data", default=str(DATA)); b.add_argument("--out", required=True)
    b.add_argument("--asap2")
    b.add_argument("--skip-missing-corpus", action="store_true",
                   help="rebuild every run that needs no corpus; skip the ASAP 2.0 runs if the corpus is absent")
    v = sub.add_parser("verify"); v.add_argument("--dump-dir", required=True); v.add_argument("--data", default=str(DATA))
    v.add_argument("--asap2")
    a = ap.parse_args()
    if a.cmd == "strip":
        strip(Path(a.dump_dir), Path(a.out))
    elif a.cmd == "rebuild":
        rebuild(Path(a.data), Path(a.out), a.asap2, a.skip_missing_corpus)
    else:
        verify(Path(a.dump_dir), Path(a.data), a.asap2)


if __name__ == "__main__":
    main()
